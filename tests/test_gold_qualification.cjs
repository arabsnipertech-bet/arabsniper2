const assert=require('node:assert/strict');
const {describe,render}=require('../web/gold-explorer-qualification.js');
assert.equal(describe({ev:.40,ev_low:.20}),null,'Numbers alone never manufacture qualification');
const row={ev:-.06,confirmation:{observation_only:false,statistical_recovery:true}};
const before=JSON.stringify(row),summary=describe(row);
assert.equal(summary.type,'statistical_recovery');
assert(summary.summary.includes('Supporto statistico'));
assert(summary.detail.includes('-6,0%'));
assert(summary.detail.includes('non certifica valore economico positivo'));
assert.equal(JSON.stringify(row),before);
const study={confirmation:{qualification_type:'study',observation_only:true,qualification_reasons:['ev_low_negative','study_only']}};
assert(render(study).includes('scenario prudente negativo'));
assert(render(study).includes('data-qualification="study"'));
assert.equal(describe({confirmation:{value_qualified:true,observation_only:true}}).type,'observation');
assert.equal(render({confirmation:{qualification_type:'<img src=x>'}}),'');
assert.equal(describe({confirmation:{observation_only:false,value_qualified:true}}).type,'documented_value');
const pick={calibrated:.459,odd:2.2,ev:.009,confirmation:{qualification_type:'study',observation_only:true,qualification_reasons:['ev_low_negative','study_only']}};
const explained=describe(pick,{role:'recommended_alternative'});
assert(explained.summary.includes('Alternativa della triade'));
assert(explained.summary.includes('45,9%'));
assert(!explained.summary.includes('negativo'));
assert(explained.detail.includes('scenario prudente negativo'));
assert.equal(explained.label,'Perché questo spunto');
const value=describe({probability:.204,odd:5.2,model_fair_odd:4.91,ev:.059,confirmation:{qualification_type:'documented_value',observation_only:false}},{role:'high_odds_shot'});
assert(value.summary.includes('20,4%'));assert(value.summary.includes('Quota 5,20 superiore alla quota equa V7 4,91'));
assert.equal(describe({probability:.9,ev:.5}),null);
assert(!render(pick).includes('open>'),'Technical limits are collapsed by default');
console.log('Gold/Explorer saved qualifications: original EV, Studio, legacy flags and no inferred promotion.');
